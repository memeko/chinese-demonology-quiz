const $ = (selector) => document.querySelector(selector);
const screens = [$("#start-screen"), $("#quiz-screen"), $("#result-screen")];
let deck = [];
let current = 0;
let score = 0;
let answered = false;
let activeMode = "classic";

function shuffle(items) {
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function prepareDeck() {
  return shuffle(questions).map((item) => {
    const answers = shuffle(item.a.map((text, index) => ({ text, isCorrect: index === item.correct })));
    return { ...item, answers };
  });
}

function showScreen(target) {
  screens.forEach((screen) => screen.classList.toggle("is-active", screen === target));
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function haptic(type = "light") {
  if (window.Telegram?.WebApp?.initData) {
    window.Telegram.WebApp.HapticFeedback?.impactOccurred(type);
  }
}

function startQuiz(mode = activeMode) {
  activeMode = typeof mode === "string" ? mode : activeMode;
  deck = activeMode === "exam"
    ? shuffle([...questions.slice(0, 32), ...examQuestions]).slice(0, 50).map((item) => ({ ...item, answers: shuffle(item.a.map((text, index) => ({ text, isCorrect: index === item.correct }))) }))
    : prepareDeck();
  current = 0;
  score = 0;
  $("#total-number").textContent = deck.length;
  $("#score-number").textContent = score;
  showScreen($("#quiz-screen"));
  renderQuestion();
}

function renderQuestion() {
  answered = false;
  const item = deck[current];
  const stage = $("#question-stage");
  stage.classList.remove("leaving");
  stage.classList.add("entering");
  setTimeout(() => stage.classList.remove("entering"), 400);
  $("#current-number").textContent = current + 1;
  $("#progress-bar").style.width = `${((current + 1) / deck.length) * 100}%`;
  $("#question-text").textContent = item.q;
  $("#next-button").disabled = true;
  $("#next-button").firstChild.textContent = current === deck.length - 1 ? "Узнать результат " : "Далее ";

  const answers = $("#answers");
  answers.replaceChildren();
  item.answers.forEach((answer, index) => {
    const button = document.createElement("button");
    button.className = "answer";
    button.type = "button";
    button.innerHTML = `<span class="answer-letter">${String.fromCharCode(65 + index)}</span><span class="answer-text"></span>`;
    button.querySelector(".answer-text").textContent = answer.text.replace(/[.。]+$/u, "");
    button.addEventListener("click", () => chooseAnswer(button, answer.isCorrect));
    answers.append(button);
  });

  const comment = $("#comment-box");
  comment.open = false;
  comment.classList.toggle("has-comment", Boolean(item.note));
  $("#comment-text").textContent = item.note || "";
}

function chooseAnswer(button, isCorrect) {
  if (answered) return;
  answered = true;
  button.classList.add("selected", isCorrect ? "correct" : "wrong");
  if (isCorrect) {
    score += 1;
    $("#score-number").textContent = score;
    haptic("light");
  } else {
    [...$("#answers").children].find((candidate, i) => deck[current].answers[i].isCorrect)?.classList.add("correct");
    haptic("heavy");
  }
  [...$("#answers").children].forEach((answer) => { answer.disabled = true; });
  $("#next-button").disabled = false;
}

function nextQuestion() {
  if (!answered) return;
  if (current === deck.length - 1) return showResult();
  $("#question-stage").classList.add("leaving");
  setTimeout(() => { current += 1; renderQuestion(); window.scrollTo({ top: 0, behavior: "smooth" }); }, 190);
}

function getClassicResult(percent) {
  if (percent <= 20) return "Поздравляем! Вы не выжили... Впрочем, если мы с вами всё ещё разговариваем, теперь бояться нужно уже вас, не так ли?";
  if (percent <= 50) return "Вас каким-то чудом нашёл странствующий даос и спас. Вы, это, поаккуратней, пожалуйста...";
  if (percent <= 70) return "О, так перед нами адепт школы заклинателей! Желаем успехов в обучении вам и терпения вашему наставнику!";
  if (percent <= 90) return "Приветствуем старшего ученика! Вы и к выпускному экзамену почти готовы, и опыт Ночной Охоты уже имеете.";
  return "Учитель, это вы?";
}

function getExamResult(percent) {
  if (percent <= 20) return "Вы точно проходили обучение? Рекомендуем вам найти школу...";
  if (percent <= 50) return "Вы знаете толк в вине, увеселительных заведениях, садах и прочем. Жаль, что наставника вы часто не слушали...";
  if (percent <= 70) return "Вы сдали, теперь вы официально заклинатель, а не просто адепт. Поздравляем! Результат мог быть и выше, но комиссия всё равно довольно вами.";
  if (percent <= 90) return "Ваш результат порадовал комиссию. Поздравляем, вы официально признаны заклинателем. Кстати, не хотите остаться преподавать?";
  return "Вы либо гений, либо замаскировавшийся учитель...Признавайтесь.";
}

function showResult() {
  const percent = Math.round((score / deck.length) * 100);
  $("#result-percent").textContent = `${percent}%`;
  $("#result-count").textContent = `${score} из ${deck.length}`;
  $("#result-message").textContent = activeMode === "exam" ? getExamResult(percent) : getClassicResult(percent);
  $("#result-overline").textContent = activeMode === "exam" ? "Экзамен завершён" : "Испытание завершено";
  $("#result-seal").textContent = percent > 90 ? "师" : percent > 50 ? "成" : "命";
  showScreen($("#result-screen"));
  if (window.Telegram?.WebApp?.initData) {
    window.Telegram.WebApp.HapticFeedback?.notificationOccurred(percent > 50 ? "success" : "warning");
  }
}

document.querySelectorAll("[data-mode]").forEach((button) => button.addEventListener("click", () => startQuiz(button.dataset.mode)));
$("#restart-button").addEventListener("click", () => startQuiz(activeMode));
$("#next-button").addEventListener("click", nextQuestion);
$("#exit-button").addEventListener("click", () => showScreen($("#start-screen")));

if (window.Telegram?.WebApp?.initData) {
  window.Telegram.WebApp.ready();
  window.Telegram.WebApp.expand();
  window.Telegram.WebApp.setHeaderColor("#0a0d0d");
  window.Telegram.WebApp.setBackgroundColor("#080b0b");
}
